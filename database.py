import sqlite3
from datetime import datetime, timedelta
import random

DB_NAME = "farm_data.db"


def get_connection():
    """
    Creates and returns a connection to the SQLite database.
    row_factory is set to sqlite3.Row so we can access columns by name!
    """
    conn = sqlite3.connect(DB_NAME)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    """
    Initializes the database table if it doesn't already exist.
    Called once when the app starts up.
    """
    conn = get_connection()
    cursor = conn.cursor()

    # Create the sensor_readings table
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS sensor_readings (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp TEXT NOT NULL,
            crop_name TEXT NOT NULL,
            zone_id TEXT NOT NULL,
            moisture REAL NOT NULL,
            temperature REAL NOT NULL,
            humidity REAL NOT NULL,
            ph REAL NOT NULL,
            status TEXT NOT NULL,
            advisory TEXT NOT NULL
        )
    """)
    conn.commit()
    conn.close()

    # Seed initial data if the table is empty so the dashboard has rich visuals
    seed_mock_data_if_empty()


def insert_reading(crop_name, zone_id, moisture, temperature, humidity, ph, status, advisory):
    """
    Inserts a single sensor reading record into the database.
    
    Parameters:
        crop_name (str): Type of crop (e.g. Wheat, Tomato, Rice)
        zone_id (str): Farm sector/zone (e.g. Zone A - North Field)
        moisture (float): Soil moisture in percentage (0 - 100%)
        temperature (float): Ambient temperature in Celsius (°C)
        humidity (float): Relative air humidity in percentage (0 - 100%)
        ph (float): Soil acidity level (0 - 14)
        status (str): Overall health status ('Optimal', 'Warning', 'Critical')
        advisory (str): Rule-based action recommendation generated by engine
    """
    conn = get_connection()
    cursor = conn.cursor()

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    cursor.execute("""
        INSERT INTO sensor_readings 
        (timestamp, crop_name, zone_id, moisture, temperature, humidity, ph, status, advisory)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (timestamp, crop_name, zone_id, moisture, temperature, humidity, ph, status, advisory))

    conn.commit()
    conn.close()


def get_latest_reading():
    """
    Retrieves the most recent sensor entry from the database.
    Returns a dict representation or None if empty.
    """
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT * FROM sensor_readings 
        ORDER BY id DESC LIMIT 1
    """)
    row = cursor.fetchone()
    conn.close()

    if row:
        return dict(row)
    return None


def get_all_readings(limit=100):
    """
    Retrieves the recent sensor entries sorted by newest first.
    Returns a list of dicts.
    """
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT * FROM sensor_readings 
        ORDER BY id DESC LIMIT ?
    """, (limit,))
    rows = cursor.fetchall()
    conn.close()

    return [dict(row) for row in rows]


def get_readings_chronological(limit=30):
    """
    Retrieves records in chronological order (oldest to newest)
    specifically for time-series trend plotting.
    """
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT * FROM (
            SELECT * FROM sensor_readings 
            ORDER BY id DESC LIMIT ?
        ) ORDER BY id ASC
    """, (limit,))
    rows = cursor.fetchall()
    conn.close()

    return [dict(row) for row in rows]


